class UserProfile {
  String name;
  String fullName;
  String email;
  String dob;
  double height; // cm
  double weight; // kg
  String lastPeriodStart; // YYYY-MM-DD
  int cycleLength; // days
  int periodLength; // days
  String partnerCode; // 6-digit auto-generated by Supabase
  String role; // 'utama' | 'pasangan'

  UserProfile({
    this.name = '',
    this.fullName = '',
    this.email = '',
    this.dob = '',
    this.height = 0,
    this.weight = 0,
    this.lastPeriodStart = '',
    this.cycleLength = 0,
    this.periodLength = 0,
    this.partnerCode = '',
    this.role = 'utama',
  });

  UserProfile copyWith({
    String? name,
    String? fullName,
    String? email,
    String? dob,
    double? height,
    double? weight,
    String? lastPeriodStart,
    int? cycleLength,
    int? periodLength,
    String? partnerCode,
    String? role,
  }) {
    return UserProfile(
      name: name ?? this.name,
      fullName: fullName ?? this.fullName,
      email: email ?? this.email,
      dob: dob ?? this.dob,
      height: height ?? this.height,
      weight: weight ?? this.weight,
      lastPeriodStart: lastPeriodStart ?? this.lastPeriodStart,
      cycleLength: cycleLength ?? this.cycleLength,
      periodLength: periodLength ?? this.periodLength,
      partnerCode: partnerCode ?? this.partnerCode,
      role: role ?? this.role,
    );
  }

  Map<String, dynamic> toJson() => {
    'name': name,
    'fullName': fullName,
    'email': email,
    'dob': dob,
    'height': height,
    'weight': weight,
    'lastPeriodStart': lastPeriodStart,
    'cycleLength': cycleLength,
    'periodLength': periodLength,
    'partnerCode': partnerCode,
    'role': role,
  };

  factory UserProfile.fromJson(Map<String, dynamic> json) => UserProfile(
    name: json['name'] ?? '',
    fullName: json['fullName'] ?? '',
    email: json['email'] ?? '',
    dob: json['dob'] ?? '',
    height: (json['height'] ?? 0).toDouble(),
    weight: (json['weight'] ?? 0).toDouble(),
    lastPeriodStart: json['lastPeriodStart'] ?? '',
    cycleLength: json['cycleLength'] ?? 0,
    periodLength: json['periodLength'] ?? 0,
    partnerCode: json['partnerCode'] ?? '',
    role: json['role'] ?? 'utama',
  );
}

