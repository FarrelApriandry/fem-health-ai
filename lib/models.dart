enum AppLanguage { indonesia, english }

class AppSettings {
  AppLanguage language;

  String theme;
  bool pinLockEnabled;
  bool biometricsEnabled;
  String pinCode;

  AppSettings({
    this.language = AppLanguage.indonesia,
    this.theme = 'light',
    this.pinLockEnabled = true,
    this.biometricsEnabled = true,
    this.pinCode = '1234',
  });

  AppSettings copy() {
    return AppSettings(
      language: language,
      theme: theme,
      pinLockEnabled: pinLockEnabled,
      biometricsEnabled: biometricsEnabled,
      pinCode: pinCode,
    );
  }

  Map<String, dynamic> toJson() => {
    'language': language.name,
    'theme': theme,
    'pinLockEnabled': pinLockEnabled,
    'biometricsEnabled': biometricsEnabled,
    'pinCode': pinCode,
  };

  factory AppSettings.fromJson(Map<String, dynamic> json) => AppSettings(
    language: AppLanguage.values.firstWhere(
      (e) => e.name == json['language'],
      orElse: () => AppLanguage.indonesia,
    ),
    theme: json['theme'] ?? 'light',
    pinLockEnabled: json['pinLockEnabled'] ?? true,
    biometricsEnabled: json['biometricsEnabled'] ?? true,
    pinCode: json['pinCode'] ?? '1234',
  );
}

class PartnerConnection {
  final String id;
  final String requesterId;
  final String receiverId;
  final String status; // 'pending' | 'accepted' | 'rejected'
  final DateTime createdAt;

  PartnerConnection({
    required this.id,
    required this.requesterId,
    required this.receiverId,
    required this.status,
    required this.createdAt,
  });

  factory PartnerConnection.fromJson(Map<String, dynamic> json) =>
      PartnerConnection(
        id: json['id'] ?? '',
        requesterId: json['requester_id'] ?? '',
        receiverId: json['receiver_id'] ?? '',
        status: json['status'] ?? 'pending',
        createdAt: json['created_at'] != null
            ? DateTime.parse(json['created_at'])
            : DateTime.now(),
      );

  Map<String, dynamic> toJson() => {
    'id': id,
    'requester_id': requesterId,
    'receiver_id': receiverId,
    'status': status,
    'created_at': createdAt.toIso8601String(),
  };
}

