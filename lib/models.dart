class DailyLog {
  final String date; // YYYY-MM-DD
  final String? mood; // 'terrible' | 'bad' | 'okay' | 'good' | 'great'
  final List<String> symptoms;
  final int severity; // 1-5
  final String personalNotes;
  final SleepLog? sleep;
  final List<HydrationLog>? hydrationLogs;
  final int hydrationGoal;

  DailyLog({
    required this.date,
    this.mood,
    this.symptoms = const [],
    this.severity = 3,
    this.personalNotes = '',
    this.sleep,
    this.hydrationLogs,
    this.hydrationGoal = 2500,
  });

  DailyLog copyWith({
    String? mood,
    List<String>? symptoms,
    int? severity,
    String? personalNotes,
    SleepLog? sleep,
    List<HydrationLog>? hydrationLogs,
    int? hydrationGoal,
  }) {
    return DailyLog(
      date: date,
      mood: mood ?? this.mood,
      symptoms: symptoms ?? this.symptoms,
      severity: severity ?? this.severity,
      personalNotes: personalNotes ?? this.personalNotes,
      sleep: sleep ?? this.sleep,
      hydrationLogs: hydrationLogs ?? this.hydrationLogs,
      hydrationGoal: hydrationGoal ?? this.hydrationGoal,
    );
  }

  Map<String, dynamic> toJson() => {
    'date': date,
    'mood': mood,
    'symptoms': symptoms,
    'severity': severity,
    'personalNotes': personalNotes,
    'sleep': sleep?.toJson(),
    'hydrationLogs': hydrationLogs?.map((e) => e.toJson()).toList(),
    'hydrationGoal': hydrationGoal,
  };

  factory DailyLog.fromJson(Map<String, dynamic> json) => DailyLog(
    date: json['date'] ?? '',
    mood: json['mood'],
    symptoms: (json['symptoms'] as List?)?.cast<String>() ?? const [],
    severity: json['severity'] ?? 3,
    personalNotes: json['personalNotes'] ?? '',
    sleep: json['sleep'] != null ? SleepLog.fromJson(json['sleep']) : null,
    hydrationLogs: (json['hydrationLogs'] as List?)
        ?.map((e) => HydrationLog.fromJson(e))
        .toList(),
    hydrationGoal: json['hydrationGoal'] ?? 2500,
  );
}

